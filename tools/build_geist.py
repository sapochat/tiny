"""Offline bounded gray4 Geist atlas. Source font is the approved concept's embedded font.
Requires Pillow; no network access. Baseline-top coordinates, integer advances.
"""
from pathlib import Path
import hashlib, json
from PIL import Image, ImageDraw, ImageFont, __version__
ROOT=Path(__file__).resolve().parents[1]
source=ROOT/'assets/fonts/Geist-Regular.ttf'
sizes=[14,18,24,30]
# Runtime lookup uses std::lower_bound: all faces must share a strictly
# increasing, duplicate-free table. Never rely on insertion order here.
codes=sorted(set(list(range(32,127))+list(range(160,256))+[0x2013,0x2014,0x2018,0x2019,0x201c,0x201d,0x2026,0x2191,0x2193,0x203a,0xfffd]))
assert codes and all(a<b for a,b in zip(codes,codes[1:]))
assert all(0<=cp<=0x10ffff and not 0xd800<=cp<=0xdfff for cp in codes)
fallback_index=codes.index(0xfffd)
assert 0<=fallback_index<len(codes) and codes[fallback_index]==0xfffd
data=[]; glyphs=[]; fonts=[]
for size in sizes:
    font=ImageFont.truetype(str(source),size)
    fonts.append((size,len(glyphs)))
    for code in codes:
        ch=chr(code)
        # Use ascender alignment so accents, capitals and descenders share baseline.
        x,y,x1,y1=map(int,font.getbbox(ch,anchor='la'))
        w,h=x1-x,y1-y
        image=Image.new('L',(max(1,w),max(1,h)))
        ImageDraw.Draw(image).text((-x,-y),ch,font=font,fill=255,anchor='la',stroke_width=0)
        coverage=[(v+8)//17 for v in image.tobytes()][:w*h]
        offset=len(data)
        i=0
        while i<len(coverage):
            end=i+1
            while end<len(coverage) and coverage[end]==coverage[i] and end-i<16: end+=1
            data.append(((end-i-1)<<4)|coverage[i])
            i=end
        glyphs.append((offset,x,y,w,h,round(font.getlength(ch))))
assert len(data)<300000
out=['// Generated by tools/build_geist.py; Geist Regular 1.800, SIL OFL-1.1.','// See assets/fonts/README.md and LICENSES/Geist-OFL.txt.','#pragma once','#include <cstdint>','namespace hg::geist_data {','struct Glyph { uint32_t offset; int8_t x,y; uint8_t w,h,advance; };',f'inline constexpr unsigned count={len(codes)};', f'inline constexpr unsigned fallback_index={fallback_index};', 'inline constexpr uint32_t codes[]={'+','.join(map(str,codes))+'};','inline constexpr unsigned sizes[]={'+','.join(map(str,sizes))+'};','inline constexpr Glyph glyphs[]={']
out += ['{'+','.join(map(str,g))+'},' for g in glyphs]
out += ['};','inline constexpr uint8_t pixels[]={']
out += [','.join(map(str,data[i:i+32]))+',' for i in range(0,len(data),32)]
out += ['};','}']
target=ROOT/'firmware/core/include/hg/geist_assets.hpp'
target.write_text('\n'.join(out)+'\n')
manifest={'font_version':'1.800','font_sha256':hashlib.sha256(source.read_bytes()).hexdigest(),'atlas_sha256':hashlib.sha256(target.read_bytes()).hexdigest(),'pillow':__version__,'sizes':sizes,'codepoints':codes,'coverage_bytes':len(data),'glyphs':len(glyphs),'format':'RLE gray4 (4-bit run minus one, 4-bit coverage), integer hinted advances, ascender anchor'}
(ROOT/'assets/fonts/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print(json.dumps({k:v for k,v in manifest.items() if k!='codepoints'},indent=2))
